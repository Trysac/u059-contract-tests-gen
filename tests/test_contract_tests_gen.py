def responses(schema: Any = None, code: str = "200") -> dict[str, Any]:
    resp: dict[str, Any] = {"description": "ok"}
    if schema is not None:
        resp["content"] = {"application/json": {"schema": schema}}
    return {code: resp}


def id_param(value: int) -> dict[str, Any]:
    return {
        "name": "id",
        "in": "path",
        "required": True,
        "schema": {"type": "integer"},
        "example": value,
    }


def make_spec() -> dict[str, Any]:
    return {
        "openapi": "3.0.3",
        "info": {"title": "t", "version": "1"},
        "paths": {
            "/a/{id}": {
                "get": {
                    "operationId": "get-users",
                    "parameters": [id_param(7)],
                    "responses": responses({"$ref": "#/components/schemas/User"}),
                }
            },
            "/b": {"get": {"operationId": "get_users", "responses": responses()}},
            "/c/{id}": {
                "delete": {
                    "operationId": "123",
                    "parameters": [id_param(3)],
                    "responses": responses(code="204"),
                }
            },
        },
        "components": {"schemas": {"User": USER}},
    }


class Fake:
    def __init__(self, status: int, body: Any) -> None:
        self.status = status
        self.body = body
        self.calls: list[tuple[str, str, dict[str, str], bytes | None]] = []

    def send(self, method: str, url: str, headers: dict[str, str], body: bytes | None) -> Response:
        self.calls.append((method, url, headers, body))
        return Response(self.status, {}, json.dumps(self.body).encode())


class Req:
    def __init__(self, transport: Any) -> None:
        self.transport = transport

    def getfixturevalue(self, name: str) -> Any:
        return self.transport


def load_module(tmp_path: Path, source: str) -> ModuleType:
    target = tmp_path / "gen_mod.py"
    target.write_text(source, encoding="utf-8")
    spec = importlib.util.spec_from_file_location("gen_mod", target)
    assert spec is not None
    assert spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_order_and_methods() -> None:
    ops = {
        m: {"operationId": m, "responses": responses()}
        for m in ["trace", "patch", "head", "options", "delete", "post", "put", "get"]
    }
    spec = {"openapi": "3.1.0", "paths": {"/z": {"get": ops["get"]}, "/m": ops}}
    ids = [c.case_id for c in extract_cases(spec)]
    assert ids == ["get", "put", "post", "delete", "options", "head", "patch", "trace", "get_2"]


def test_multiple_2xx_and_tags() -> None:
    op = {"tags": ["x"], "responses": {**responses(), **responses(code="201"), "404": {}}}
    spec = {"openapi": "3.0.0", "paths": {"/p": {"get": op, "put": {"responses": responses()}}}}
    cases = extract_cases(spec)
    assert [c.expected_status for c in cases] == [200, 201, 200]
    assert cases[0].case_id == "get__p"
    tagged = extract_cases(spec, include_tags={"x"})
    assert len(tagged) == 2
    assert extract_cases(spec, include_tags={"nope"}) == []


def test_render_deterministic_header() -> None:
    cases = extract_cases(make_spec())
    one = render_module(cases, spec_sha256=SHA)
    two = render_module(cases, spec_sha256=SHA)
    assert one == two
    assert (
        one.splitlines()[0]
        == "# Generated by contract-tests-gen from spec sha256 " + SHA + ". Do not edit."
    )
    ast.parse(one)
    for bad in ("", "x y", "a" * 129):
        with pytest.raises(ContractGenError) as err:
            render_module(cases, spec_sha256=bad)
        assert err.value.code == "invalid_spec"


