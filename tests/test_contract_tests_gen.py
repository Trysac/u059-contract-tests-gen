def test_render_errors() -> None:
    base = extract_cases(make_spec())[0]
    from dataclasses import replace

    for bad in (float("nan"), object(), {"a": {1, 2}}):
        with pytest.raises(ContractGenError) as err:
            render_module([replace(base, query={"q": bad})], spec_sha256=SHA)
        assert err.value.code == "invalid_spec"
    deep: Any = 1
    for _ in range(70):
        deep = [deep]
    with pytest.raises(ContractGenError) as err2:
        render_module([replace(base, body=deep)], spec_sha256=SHA)
    assert err2.value.code == "too_deep"
    with pytest.raises(ContractGenError):
        render_module([replace(base, expected_status=True)], spec_sha256=SHA)
    dup = render_module([base, base], spec_sha256=SHA)
    assert "def test_get_users_2(" in dup


