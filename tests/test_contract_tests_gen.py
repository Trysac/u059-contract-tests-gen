def op_with_schema(schema: Any) -> dict[str, Any]:
    return {"openapi": "3.0.0", "paths": {"/p": {"get": {"responses": responses(schema)}}}}


def test_refs() -> None:
    spec = op_with_schema({"$ref": "#/components/schemas/Node"})
    spec["components"] = {
        "schemas": {"Node": {"properties": {"next": {"$ref": "#/components/schemas/Node"}}}}
    }
    schema = extract_cases(spec)[0].response_schema
    assert schema == {"properties": {"next": {}}}
    for ref in ("#/nope", "http://x/y", "#x", "#/components/schemas/a~1b", "#/paths/%2Fq"):
        with pytest.raises(ContractGenError) as err:
            extract_cases(op_with_schema({"$ref": ref}))
        assert err.value.code == "unresolved_ref"
    with pytest.raises(ContractGenError):
        extract_cases(op_with_schema({"$ref": 5}))
    ok = op_with_schema({"$ref": "#/x/0"})
    ok["x"] = [{"type": "string"}]
    assert extract_cases(ok)[0].response_schema == {"type": "string"}
    assert extract_cases(op_with_schema({"$ref": "#"}))


def test_depth_and_size_limits() -> None:
    deep: dict[str, Any] = {"type": "string"}
