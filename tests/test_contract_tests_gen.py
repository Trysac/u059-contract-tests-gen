def test_injection() -> None:
    payload = '"' * 3 + chr(10) + "'); os.system('x'); ('"
    spec = {
        "openapi": "3.0.1",
        "paths": {
            "/p": {
                "post": {
                    "operationId": payload,
                    "description": payload,
                    "requestBody": {"content": {"application/json": {"example": {"k": payload}}}},
                    "parameters": [
                        {
                            "name": "q",
                            "in": "query",
                            "schema": {"type": "string"},
                            "example": payload,
                        }
                    ],
                    "responses": responses(
                        {"type": "string", "example": payload, "enum": [payload]}
                    ),
                }
            }
        },
    }
    source = render_module(extract_cases(spec), spec_sha256=SHA)
    tree = ast.parse(source)
    imported: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            imported |= {a.name for a in node.names}
        if isinstance(node, ast.ImportFrom):
            imported.add(node.module or "")
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute):
            assert node.func.attr != "system"
    assert imported == {"json", "os", "pytest", "contract_tests_gen.runtime"}
    assert source.count("os.environ.get") == 2


def test_generated_tests_run(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    source = render_module(extract_cases(make_spec()), spec_sha256=SHA)
    module = load_module(tmp_path, source)
    monkeypatch.setenv("CONTRACT_BASE_URL", "http://svc.test")
    monkeypatch.setenv("CONTRACT_AUTH_HEADER", "X-Token: tok")
    good = Fake(200, {"name": "x", "age": 1.0})
    module.test_get_users(Req(good))
    assert good.calls[0][1] == "http://svc.test/a/7"
    assert good.calls[0][2]["X-Token"] == "tok"
    with pytest.raises(AssertionError) as err:
        module.test_get_users(Req(Fake(200, {"age": 1})))
    assert "$: missing required property name" in str(err.value)
    with pytest.raises(AssertionError) as err2:
        module.test_get_users(Req(Fake(500, {})))
    assert "500" in str(err2.value)
    module.test_get_users_2(Req(Fake(200, {})))
    module.test_op_123(Req(Fake(204, None)))
    assert "svc.test" not in source
    assert "tok" not in source
    monkeypatch.delenv("CONTRACT_BASE_URL")
    with pytest.raises(pytest.skip.Exception):
        module.test_get_users(Req(good))


