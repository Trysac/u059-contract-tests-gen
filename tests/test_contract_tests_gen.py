def test_validator_limits() -> None:
    deep: dict[str, Any] = {"type": "string"}
    value: Any = "x"
    for _ in range(70):
        deep = {"properties": {"a": deep}}
        value = {"a": value}
    assert validate_instance(value, deep) == ["$" + ".a" * 65 + ": schema nesting too deep"]
    many = validate_instance([1] * 500, {"items": {"type": "string"}})
    assert len(many) == 100
    assert all(
        len(e) <= 200 for e in validate_instance({"k" * 500: 1}, {"additionalProperties": False})
    )


