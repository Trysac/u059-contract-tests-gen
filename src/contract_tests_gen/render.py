"""Render pytest source from contract cases."""

from __future__ import annotations

import math
import re
from collections.abc import Sequence
from typing import Any

from .errors import ContractGenError
from .spec import MAX_DEPTH, ContractCase, sanitize_id

_SHA = re.compile(r"[0-9A-Za-z]{1,128}")


def _lit(value: Any, depth: int = 0) -> str:
    """Render a plain value as a Python literal using only repr of safe types."""
    if depth > MAX_DEPTH:
        raise ContractGenError("too_deep", "value nesting too deep")
    kind = type(value)
    if value is None or kind in (bool, int, str):
        return repr(value)
    if kind is float:
        if not math.isfinite(value):
            raise ContractGenError("invalid_spec", "non-finite number in spec")
        return repr(value)
    if kind is list:
        return "[" + ", ".join(_lit(v, depth + 1) for v in value) + "]"
    if kind is dict:
        return (
            "{"
            + ", ".join(f"{_lit(k, depth + 1)}: {_lit(v, depth + 1)}" for k, v in value.items())
            + "}"
        )
    raise ContractGenError("invalid_spec", "unsupported value type in spec")


def _render_case(name: str, case: ContractCase, base_url_env: str, auth_env: str) -> str:
    if case.skip_reason is not None:
        return "\n".join(
            [
                f"@pytest.mark.skip(reason={_lit(case.skip_reason)})",
                f"def {name}() -> None:",
                "    pass",
            ]
        )
    if type(case.expected_status) is not int:
        raise ContractGenError("invalid_spec", "expected_status must be an int")
    if case.body is None:
        body_line = "    body = None"
    else:
        body_line = f'    body = json.dumps({_lit(case.body)}).encode("utf-8")'
    lines = [
        f"def {name}(request: pytest.FixtureRequest) -> None:",
        f"    base_url = os.environ.get({_lit(base_url_env)})",
        "    if not base_url:",
        '        pytest.skip("base URL environment variable is not set")',
        body_line,
        "    response = send_case(",
        "        get_transport(request),",
        "        base_url,",
        f"        os.environ.get({_lit(auth_env)}),",
        f"        {_lit(case.method.upper())},",
        f"        {_lit(case.path_template)},",
        f"        {_lit(case.path_params)},",
        f"        {_lit(case.query)},",
        "        body,",
        "    )",
        f"    errors = check_response(response, {_lit(case.expected_status)}, "
        f"{_lit(case.response_schema)})",
        '    assert not errors, "; ".join(errors)',
    ]
    return "\n".join(lines)


def render_module(
    cases: Sequence[ContractCase],
    *,
    spec_sha256: str,
    base_url_env: str = "CONTRACT_BASE_URL",
    auth_env: str = "CONTRACT_AUTH_HEADER",
) -> str:
    """Render a deterministic pytest module for ``cases``."""
    if _SHA.fullmatch(spec_sha256) is None:
        raise ContractGenError("invalid_spec", "spec_sha256 must be alphanumeric")
    head = [
        f"# Generated by contract-tests-gen from spec sha256 {spec_sha256}. Do not edit.",
        "",
        "import json  # noqa: F401",
        "import os",
        "",
        "import pytest",
        "",
        "from contract_tests_gen.runtime import check_response, get_transport, send_case",
    ]
    text = "\n".join(head)
    used: set[str] = set()
    for case in cases:
        base = f"test_{sanitize_id(case.case_id)}"
        name = base
        n = 2
        while name in used:
            name = f"{base}_{n}"
            n += 1
        used.add(name)
        text += "\n\n\n" + _render_case(name, case, base_url_env, auth_env)
    return text + "\n"
